# Normalize the database: uppercase all keys for consistent lookups
_OUI_DB: dict[str, str] = {k.upper(): v for k, v in OUI_DATABASE.items()}


def lookup_vendor(mac: str) -> str:
    """Return vendor name for a MAC address, or 'Unknown' if not found.

    Looks up the first three octets (OUI prefix) of the given MAC address
    against the embedded database.

    Args:
        mac: MAC address in XX:XX:XX:XX:XX:XX format.

    Returns:
        Vendor name string, or 'Unknown' if the OUI is not in the database.
    """
    if not mac or not isinstance(mac, str):
        return "Unknown"

    # Normalize to uppercase
    mac_upper = mac.upper().strip()

    # Extract the OUI prefix (first 3 octets)
    parts = mac_upper.split(':')
    if len(parts) < 3:
        # Try dash-separated format
        parts = mac_upper.split('-')

    if len(parts) >= 3:
        oui = ':'.join(parts[:3])
    else:
        return "Unknown"

    # Check if the locally administered bit is set (randomized MAC)
    try:
        first_octet = int(parts[0], 16)
        if first_octet & 0x02:
            return "Randomized"
    except ValueError:
        pass

    return _OUI_DB.get(oui, "Unknown")
